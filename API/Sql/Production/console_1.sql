SELECT w.PARTY_ID_SUPPLIER, p.DESCRIPTION AS supplier_name, COUNT(*) AS cert_count
FROM WORK_EFFORT w
         LEFT JOIN PARTY p ON p.PARTY_ID = w.PARTY_ID_SUPPLIER
WHERE w.WORK_EFFORT_TYPE_ID='PROJECT_CERTIFICATE'
  AND w.CERTIFICATE_CATEGORY='SUPPLY_PROCUREMENT_CERTIFICATE'
  AND w.RELATED_ORDER_ID IS NOT NULL
  AND w.PARTY_ID_SUPPLIER IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM ORDER_ITEM_BILLING oib
                      JOIN ACCTG_TRANS t ON t.INVOICE_ID = oib.INVOICE_ID
    WHERE oib.ORDER_ID = w.RELATED_ORDER_ID
)
GROUP BY w.PARTY_ID_SUPPLIER, p.DESCRIPTION
ORDER BY cert_count DESC;